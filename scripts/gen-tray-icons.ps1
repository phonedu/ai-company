# Generate tray status icons for closeout and write
# src/main/tray/icons.ts (idle / working / waiting).
# Usage: powershell -NoProfile -File scripts/gen-tray-icons.ps1
Add-Type -AssemblyName System.Drawing

function New-TrayIconBase64([string]$dotHex) {
  $bmp = New-Object System.Drawing.Bitmap(32, 32)
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
  $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
  $g.Clear([System.Drawing.Color]::Transparent)

  $path = New-Object System.Drawing.Drawing2D.GraphicsPath
  $r = 7
  $path.AddArc(3, 3, $r, $r, 180, 90)
  $path.AddArc(29 - $r, 3, $r, $r, 270, 90)
  $path.AddArc(29 - $r, 29 - $r, $r, $r, 0, 90)
  $path.AddArc(3, 29 - $r, $r, $r, 90, 90)
  $path.CloseFigure()
  $baseBrush = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 51, 65, 85))
  $g.FillPath($baseBrush, $path)

  $font = New-Object System.Drawing.Font('Segoe UI', 13, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
  $white = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 248, 250, 252))
  $fmt = New-Object System.Drawing.StringFormat
  $fmt.Alignment = [System.Drawing.StringAlignment]::Center
  $fmt.LineAlignment = [System.Drawing.StringAlignment]::Center
  $rect = New-Object System.Drawing.RectangleF(0, -1, 32, 32)
  $g.DrawString('A', $font, $white, $rect, $fmt)

  if ($dotHex) {
    $dot = [System.Drawing.ColorTranslator]::FromHtml($dotHex)
    $ring = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 248, 250, 252))
    $fill = New-Object System.Drawing.SolidBrush($dot)
    $g.FillEllipse($ring, 18, 18, 12, 12)
    $g.FillEllipse($fill, 20, 20, 8, 8)
  }

  $ms = New-Object System.IO.MemoryStream
  $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
  $b64 = [Convert]::ToBase64String($ms.ToArray())
  $g.Dispose()
  $bmp.Dispose()
  $ms.Dispose()
  return $b64
}

$idle = New-TrayIconBase64 ''
$working = New-TrayIconBase64 '#22c55e'
$waiting = New-TrayIconBase64 '#f59e0b'

$lines = @(
  '// Generated by scripts/gen-tray-icons.ps1. Do not edit by hand.',
  '// 32x32 PNG data URLs: idle / working (green dot) / waiting (orange dot).',
  'export const TRAY_ICON_PNG_BASE64 = {',
  ("  idle: '{0}'," -f $idle),
  ("  working: '{0}'," -f $working),
  ("  waiting: '{0}'," -f $waiting),
  '} as const;',
  ''
)
$target = Join-Path $PSScriptRoot '..\src\main\tray\icons.ts'
$lines | Set-Content -Encoding ASCII -Path $target
Write-Output ("wrote {0}" -f (Resolve-Path $target))
