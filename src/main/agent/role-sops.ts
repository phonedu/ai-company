/** 精确匹配角色名取 SOP；未匹配 → null（回落 roleLayer 两句话，幕僚长 draft_sop 可补）。 */
export function sopFor(role: string): RoleSop | null {
  return ROLE_SOP_PRESETS[role.trim()] ?? null;
}

/** SOP 组装成提示词分节（静态段）。 */
export function renderSopLayer(sop: RoleSop): string {
  return [
    `[角色 SOP · ${sop.role}]`,
    '## 工作方法',
    sop.method,
    '## 输出规范',
    sop.outputSpec,
    '## 交付前自检',
    sop.checklist,
  ].join('\n');
}
